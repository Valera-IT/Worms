using System;

/// Канал доставки. Ввод активного игрока идёт без гарантий — потерянный
/// кадр ввода не стоит того, чтобы ждать его повтора и задерживать всё
/// остальное. Смена хода, старт матча и сверка состояния идут надёжно.
public enum NetChannel : byte
{
    Unreliable = 0,
    Reliable = 1
}

/// Как байты попадают от одного устройства к другому. Всё, что выше —
/// комната, ввод, состояние мира — с этим интерфейсом и работает и про
/// сокеты не знает.
///
/// Смысл разделения в порядке работ: сейчас за интерфейсом стоят петля в
/// одном процессе (для тестов) и UDP по адресу (для игры в одной сети),
/// а Relay от Unity Gaming Services встанет туда же третьей реализацией,
/// когда дойдут руки до кода комнаты через интернет. Ни одна строка
/// игровой логики от этого не поменяется.
public interface INetTransport : IDisposable
{
    bool IsHost { get; }

    /// Соединение живо: у хоста — сокет поднят, у клиента — хост отвечает.
    bool Connected { get; }

    /// Номер этого устройства. У хоста всегда 0.
    int LocalPeer { get; }

    /// Раз в кадр: разгрести входящие пакеты и переслать неподтверждённое.
    void Tick();

    /// Отправить одному. У клиента адресат игнорируется — он умеет говорить
    /// только с хостом.
    void Send(int peer, byte[] data, int length, NetChannel channel);

    /// Отправить всем, кроме указанного (-1 — вообще всем).
    void Broadcast(byte[] data, int length, NetChannel channel, int except = -1);

    /// Появился новый участник. Только у хоста.
    event Action<int> PeerJoined;

    /// Участник ушёл или замолчал. У клиента приходит с номером хоста, когда
    /// связь потеряна.
    event Action<int> PeerLeft;

    /// Пришли байты: от кого, сам буфер и сколько в нём значащих байт.
    /// Буфер переиспользуется — за пределы обработчика его тащить нельзя.
    event Action<int, byte[], int> Received;

    /// Задержка до участника в миллисекундах, -1 если ещё не мерили.
    int PingTo(int peer);
}
