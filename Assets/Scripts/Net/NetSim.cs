/// Кто в этом процессе считает бой по-настоящему.
///
/// Offline и хост — считают: физика, урон, воронки, ход. Клиент — показывает:
/// он крутит ту же физику ради живой картинки, но всё, что меняет состояние
/// мира необратимо, у него выключено и приходит от хоста. Разделение сделано
/// одним флагом, а не ветвлением по всему коду: места, где авторитет важен,
/// наперечёт, и каждое из них видно поиском по NetSim.
public static class NetSim
{
    /// true — этот процесс сам решает, что произошло.
    public static bool Authority = true;

    /// Идёт применение того, что прислал хост: на время этого флага запреты
    /// клиента сняты, иначе он отбрасывал бы и хостовые изменения тоже.
    public static bool Applying;

    /// Клиент, и прямо сейчас не применяет присланное.
    public static bool Mirror => !Authority && !Applying;

    public static void Reset()
    {
        Authority = true;
        Applying = false;
    }
}
